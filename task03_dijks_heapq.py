# Імпортуємо модуль heapq — стандартну мін-купу (бінарну піраміду) для швидкого вибору мінімального елемента
import heapq
# Імпортуємо networkx для роботи з графами (створення, зберігання ваг тощо)
import networkx as nx
# Імпортуємо matplotlib для візуалізації графа (не обов'язково для Дейкстри, але зручно для огляду)
import matplotlib.pyplot as plt


# Створюємо порожній неорієнтований граф (ваги будемо зберігати в атрибуті 'weight' ребра)
G = nx.Graph()
# Додаємо ребро A-B з вагою 4 (відстань між вершинами A і B)
G.add_edge("A", "B", weight=4)
# Додаємо ребро A-C з вагою 2
G.add_edge("A", "C", weight=2)
# Додаємо ребро B-C з вагою 5 (альтернативний, гірший шлях між B і C)
G.add_edge("B", "C", weight=5)
# Додаємо ребро B-D з вагою 10  
G.add_edge("B", "D", weight=10)
# Додаємо ребро C-E з вагою 3
G.add_edge("C", "E", weight=3)
# Додаємо ребро E-D з вагою 4 (через E до D — зазвичай вигідніше, ніж напряму з B)
G.add_edge("E", "D", weight=4)
# Додаємо ребро D-F з вагою 11
G.add_edge("D", "F", weight=11)
# Додаємо ребро E-F з вагою 5 (часто найкоротший шлях до F йтиме через E)
G.add_edge("E", "F", weight=5)


# Оголошуємо функцію dijkstra, яка отримує граф 'graph' і стартову вершину 'start'
def dijkstra(graph: nx.Graph, start):
    # Створюємо словник найкоротших відстаней: спочатку всі нескінченні (∞)
    distances = {vertex: float("inf") for vertex in graph.nodes}
    # Для стартової вершини відстань 0 (мінімум по визначенню)
    distances[start] = 0
    # Створюємо словник попередників для відновлення шляху (хто передував кожній вершині у найкоротшому шляху)
    previous = {vertex: None for vertex in graph.nodes}

    # Ініціалізуємо мін-купу (пріоритетну чергу); кладемо кортеж (поточна_відстань, вершина)
    heap = []
    # Кладемо стартову вершину з відстанню 0 — саме з неї почнемо «розпускати» найкоротші шляхи
    heapq.heappush(heap, (0, start))

    # Поки у купі є елементи — беремо вершину з найменшою поточною відстанню
    while heap:
        # Дістаємо вершину з мінімальною оцінкою відстані (жадібний вибір)
        current_dist, u = heapq.heappop(heap)

        # Перевіряємо «ледачі» (lazy) записи: якщо ми вже знайшли кращу відстань до 'u', пропускаємо цей запис
        if current_dist > distances[u]:
            # Продовжуємо цикл, оскільки в купі може бути застарілий запис з більшою відстанню
            continue

        # Для кожного сусіда 'v' вершини 'u' переглядаємо ребро (u, v)
        for v, attrs in graph[u].items():
            # Дістаємо вагу ребра (u, v); за замовчуванням припустимо 1, але у нас вона завжди задана
            w = attrs.get("weight", 1)

            # Перевірка на коректність ваг для Дейкстри: алгоритм коректний лише для не від’ємних ваг
            if w < 0:
                # Якщо вага від’ємна — кидаємо виключення, щоб привернути увагу до невірних даних
                raise ValueError("Алгоритм Дейкстри не працює з від’ємними вагами.")

            # Обчислюємо потенційно нову найкоротшу відстань до 'v' через 'u'
            new_dist = current_dist + w

            # Якщо нова відстань краща за ту, що вже записана у 'distances[v]' — оновлюємо результат
            if new_dist < distances[v]:
                # Оновлюємо найкоротшу відстань до 'v'
                distances[v] = new_dist
                # Запам’ятовуємо, що найкращий шлях до 'v' веде через 'u'
                previous[v] = u
                # Кладемо оновлений кортеж (новий_пріоритет, вершина) назад у мін-купу
                heapq.heappush(heap, (new_dist, v))

    # Повертаємо словник найкоротших відстаней і попередників для відновлення шляхів
    return distances, previous


# Оголошуємо допоміжну функцію для відновлення шляху з 'start' до 'target' за словником 'previous'
def reconstruct_path(previous: dict, start, target):
    # Починаємо з цільової вершини та рухаємося назад через попередників
    path = []
    # Тимчасова змінна для ходіння назад ланцюжком попередників
    cur = target
    # Ідемо доти, доки не дійдемо до None (або до старту)
    while cur is not None:
        # Додаємо поточну вершину у маршрут
        path.append(cur)
        # Переходимо до попередника
        cur = previous[cur]
    # Реверсуємо список, щоб отримати шлях від start до target
    path.reverse()
    # Якщо шлях порожній або не починається зі start (наприклад, ціль недосяжна) — повернемо порожній список
    if not path or path[0] != start:
        # Недосяжний випадок — порожній шлях
        return []
    # Інакше повертаємо відновлений шлях
    return path


# Вказуємо стартову вершину, від якої рахуємо найкоротші шляхи
start = "A"
# Запускаємо алгоритм Дейкстри на графі G зі старту 'A'
distances, previous = dijkstra(G, start)
# Друкуємо словник найкоротших відстаней від 'A' до всіх вершин
print("Найкоротші відстані від A:", distances)

# Для прикладу відновимо найкоротший шлях від 'A' до 'F'
target = "F"
# Викликаємо відновлення шляху за попередниками
path_AF = reconstruct_path(previous, start, target)
# Виводимо знайдений маршрут (якщо він існує)
print(f"Найкоротший шлях {start} → {target}:", " -> ".join(path_AF) if path_AF else "шляху немає")

# Обчислюємо позиції вершин для візуалізації (spring_layout — силовий алгоритм для гарного розташування)
pos = nx.spring_layout(G, seed=42)
# Малюємо вершини (кружечки), розмір кожної — 700
nx.draw_networkx_nodes(G, pos, node_size=700)
# Малюємо ребра (лінії між вершинами), товщина — 2
nx.draw_networkx_edges(G, pos, width=2)
# Підписуємо ваги на ребрах (беремо атрибут 'weight' кожного ребра)
edge_labels = nx.get_edge_attributes(G, "weight")
# Малюємо текстові підписи ваг на відповідних ребрах
nx.draw_networkx_edge_labels(G, pos, edge_labels=edge_labels)
# Підписуємо вершини літерами (A, B, C, …)
nx.draw_networkx_labels(G, pos, font_size=16, font_family="sans-serif")

# Вимикаємо осі координат, щоб малюнок виглядав чистіше
plt.axis("off")
# Показуємо побудований граф на екрані
plt.show()