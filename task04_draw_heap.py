if __name__ == '__main__':
    # Оголошуємо вихідний список значень, який інтерпретуємо як купу/індексне дерево
    heap_list = [0, 4, 1, 5, 10, 3]
    # Перетворюємо список на мін-купу (heapq гарантує, що батьківський елемент не більший за дітей)
    heapq.heapify(heap_list)
    # Виводимо отриману купу у консоль (щоб бачити, як вона виглядає після heapify)
    print(heap_list)

    # Будуємо зв’язне Node-дерево з масиву-купи, використовуючи формули індексів
    heap_tree_root = build_heap_tree(heap_list)

    # Викликаємо функцію візуалізації — намалює дерево, що відповідає бінарній купі
    draw_tree(heap_tree_root)



