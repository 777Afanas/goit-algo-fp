# Імпортуємо модуль uuid — він дозволить створювати унікальні ідентифікатори (рядки UUID) для кожного вузла дерева
import uuid
# Імпортуємо модуль heapq — використаємо його, щоб перетворити список на мін-купу (підтвердити купову властивість)
import heapq

# Імпортуємо бібліотеку networkx — вона надає структури даних і функції для роботи з графами (дерево малюватимемо як граф)
import networkx as nx
# Імпортуємо matplotlib.pyplot — інструмент для візуалізації графів (малювання вузлів і ребер на площині)
import matplotlib.pyplot as plt


# Оголошуємо клас Node — елементарний вузол бінарного дерева
class Node:
    # Визначаємо конструктор, який приймає значення вузла (key) і початковий колір (color)
    def __init__(self, key, color="skyblue"):
        # Ініціалізуємо посилання на лівого нащадка (спочатку відсутній — None)
        self.left = None
        # Ініціалізуємо посилання на правого нащадка (спочатку відсутній — None)
        self.right = None
        # Зберігаємо значення вузла (буде відображатися у підписі при візуалізації)
        self.val = key
        # Зберігаємо колір вузла (можна змінювати пізніше, але тут достатньо дефолтного)
        self.color = color
        # Генеруємо та зберігаємо унікальний рядковий ідентифікатор вузла (потрібен як стабільний ключ у графі)
        self.id = str(uuid.uuid4())  # Унікальний ідентифікатор для кожного вузла


# Описуємо допоміжну функцію add_edges — вона наповнює граф вершинами та ребрами, обходячи дерево від заданого вузла
def add_edges(graph, node, pos, x=0, y=0, layer=1):
    # Перевіряємо, що вузол існує; якщо None — нічого додавати не потрібно
    if node is not None:
        # Додаємо у граф вершину з ключем node.id та двома атрибутами:
        # 'color' — колір вузла, 'label' — текст мітки (значення вузла)
        graph.add_node(node.id, color=node.color, label=node.val)  # Використання id та збереження значення вузла
        # Якщо у вузла є лівий нащадок — додаємо ребро та рекурсивно обробляємо ліве піддерево
        if node.left:
            # Додаємо орієнтоване ребро від поточного вузла до лівого нащадка
            graph.add_edge(node.id, node.left.id)
            # Обчислюємо нову X-координату для лівого вузла:
            # чим глибше шар (layer), тим менший горизонтальний зсув
            l = x - 1 / 2 ** layer
            # Фіксуємо позицію лівого вузла на площині (трохи лівіше та на рівень нижче)
            pos[node.left.id] = (l, y - 1)
            # Рекурсивно додаємо вершини та ребра для лівого піддерева (поглиблюємося на один шар)
            add_edges(graph, node.left, pos, x=l, y=y - 1, layer=layer + 1)
        # Якщо у вузла є правий нащадок — додаємо ребро та рекурсивно обробляємо праве піддерево
        if node.right:
            # Додаємо орієнтоване ребро від поточного вузла до правого нащадка
            graph.add_edge(node.id, node.right.id)
            # Обчислюємо нову X-координату для правого вузла (дзеркально до лівого)
            r = x + 1 / 2 ** layer
            # Фіксуємо позицію правого вузла (трохи правіше та на рівень нижче)
            pos[node.right.id] = (r, y - 1)
            # Рекурсивно додаємо вершини та ребра для правого піддерева (поглиблюємося на один шар)
            add_edges(graph, node.right, pos, x=r, y=y - 1, layer=layer + 1)
    # Повертаємо посилання на граф — це зручно для ланцюжкових викликів (хоч і не обов’язково)
    return graph


# Описуємо функцію draw_tree — вона будує граф з дерева та малює його
def draw_tree(tree_root):
    # Створюємо порожній орієнтований граф (вузли матимуть напрямлені ребра від батьків до дітей)
    tree = nx.DiGraph()
    # Визначаємо початкову позицію для кореня (ставимо його у центр координат)
    pos = {tree_root.id: (0, 0)}
    # Наповнюємо граф вершинами та ребрами, використовуючи допоміжну функцію
    tree = add_edges(tree, tree_root, pos)

    # Формуємо список кольорів для всіх вершин у порядку їх появи у graph.nodes(data=True)
    colors = [node[1]['color'] for node in tree.nodes(data=True)]
    # Формуємо словник підписів для вершин: ключ — id вершини, значення — мітка (label), тобто значення вузла
    labels = {node[0]: node[1]['label'] for node in tree.nodes(data=True)}  # Використовуйте значення вузла для міток

    # Створюємо полотно для малювання (8x5 дюймів — достатньо для невеликого дерева)
    plt.figure(figsize=(8, 5))
    # Малюємо граф:
    #  - pos — попередньо розраховані координати
    #  - labels — підписи на вершинах
    #  - arrows=False — стрілки на ребрах не потрібні (дерево читається і без них)
    #  - node_size — розмір кола вершини
    #  - node_color — список кольорів для кожної вершини
    nx.draw(tree, pos=pos, labels=labels, arrows=False, node_size=2500, node_color=colors)
    # Відображаємо отриману картинку у вікні/ноутбуці
    plt.show()


# Описуємо функцію build_heap_tree — вона з масиву (купоподібного представлення) будує зв’язане Node-дерево
def build_heap_tree(heap, index=0):
    # Якщо список порожній — будувати нічого, одразу повертаємо None
    if not heap:
        return None

    # Створюємо список вузлів тієї ж довжини:
    #  - якщо елемент у масиві None — лишаємо None (пропуск у дереві)
    #  - інакше створюємо Node зі значенням елемента
    nodes = [None if v is None else Node(v) for v in heap]

    # Обчислюємо загальну кількість позицій (зручно зберегти у змінну, щоб не рахувати щораз)
    n = len(nodes)
    # Проходимо всі індекси та прив’язуємо дітей до батьків
    for i, node in enumerate(nodes):
        # Якщо в поточній позиції вузол відсутній — нічого прив’язувати, переходимо далі
        if node is None:
            continue
        # Обчислюємо індекс лівого нащадка за формулою для бінарної купи: 2*i + 1
        left = 2 * i + 1
        # Обчислюємо індекс правого нащадка за формулою: 2*i + 2
        right = 2 * i + 2
        # Якщо індекс лівого у межах списку — прив’язуємо посилання на лівого (може бути None)
        if left < n:
            node.left = nodes[left]
        # Якщо індекс правого у межах списку — прив’язуємо посилання на правого (може бути None)
        if right < n:
            node.right = nodes[right]

    # Повертаємо корінь побудованого дерева — перший елемент (індекс 0) у списку вузлів
    return nodes[0]


