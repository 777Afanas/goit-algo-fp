# Імпортуємо модуль uuid (залишаємо для сумісності з оригінальним кодом, де він використовувався в класі Node)
import uuid
# Імпортуємо бібліотеку networkx для побудови графів (використаємо для подання дерева як графа)
import networkx as nx
# Імпортуємо matplotlib.pyplot для візуалізації графа (малювання вершин та ребер)
import matplotlib.pyplot as plt


# Описуємо клас Node з оригінального прикладу (зберігаємо «як є» для повної сумісності)
# Примітка: у новій реалізації на основі масиву/списку ми НЕ використовуємо цей клас,
# але залишаємо його в коді, бо ви просили врахувати всі початкові функції/класи.
class Node:
  # Конструктор приймає ключ (значення вузла) та необов’язковий колір
  def __init__(self, key, color="skyblue"):
    # Поле для посилання на лівого нащадка (не використовується у варіанті зі списком)
    self.left = None
    # Поле для посилання на правого нащадка (не використовується у варіанті зі списком)
    self.right = None
    # Значення вузла (корисно для підписів)
    self.val = key
    # Колір вузла для візуалізації
    self.color = color
    # Унікальний ідентифікатор (UUID) для вузла (залишається для сумісності з оригіналом)
    self.id = str(uuid.uuid4())


# Функція add_edges тепер працює з ПРЕДСТАВЛЕННЯМ КУПИ ЯК СПИСКУ (heap) та ІНДЕКСОМ i,
# а не з об’єктами Node; ім'я функції збережено для сумісності з оригіналом.
def add_edges(graph, heap, i, pos, x=0, y=0, layer=1):
  # Перевіряємо, що індекс i всередині меж списку та поточний елемент існує (не None)
  if 0 <= i < len(heap) and heap[i] is not None:
    # Додаємо вершину з ідентифікатором i; зберігаємо колір і мітку (значення) як атрибути
    graph.add_node(i, color="skyblue", label=heap[i])

    # Обчислюємо індекси дітей за формулами бінарної купи
    left = 2 * i + 1   # індекс лівого нащадка
    right = 2 * i + 2  # індекс правого нащадка

    # Якщо лівий нащадок існує та не None — проводимо ребро і рекурсивно додаємо його піддерево
    if left < len(heap) and heap[left] is not None:
      # Додаємо орієнтоване ребро від батька (i) до лівого нащадка (left)
      graph.add_edge(i, left)
      # Обчислюємо «горизонтальне» зміщення для лівого вузла на поточному шарі
      lx = x - 1 / (2 ** layer)
      # Фіксуємо позицію лівого вузла: зміщуємо вниз по Y і вліво по X
      pos[left] = (lx, y - 1)
      # Рекурсивно додаємо ліве піддерево, збільшуючи глибину шару
      add_edges(graph, heap, left, pos, x=lx, y=y - 1, layer=layer + 1)

    # Якщо правий нащадок існує та не None — проводимо ребро і рекурсивно додаємо його піддерево
    if right < len(heap) and heap[right] is not None:
      # Додаємо орієнтоване ребро від батька (i) до правого нащадка (right)
      graph.add_edge(i, right)
      # Обчислюємо «горизонтальне» зміщення для правого вузла на поточному шарі
      rx = x + 1 / (2 ** layer)
      # Фіксуємо позицію правого вузла: зміщуємо вниз по Y і вправо по X
      pos[right] = (rx, y - 1)
      # Рекурсивно додаємо праве піддерево, збільшуючи глибину шару
      add_edges(graph, heap, right, pos, x=rx, y=y - 1, layer=layer + 1)

  # Повертаємо граф (для сумісності з оригінальним патерном використання)
  return graph


# Функція draw_tree зберігає назву та логіку побудови графа, але тепер
# приймає на вхід СПИСОК heap — представлення бінарної купи.
def draw_tree(heap):
  # Перевіряємо, що купа не порожня і що корінь існує
  if not heap or heap[0] is None:
    # Якщо кореня немає — просто нічого не малюємо і повертаємося
    return

  # Створюємо порожній орієнтований граф для зображення дерева
  tree = nx.DiGraph()
  # Ініціалізуємо словник позицій координатою кореня (індекс 0) у точці (0, 0)
  pos = {0: (0, 0)}
  # Рекурсивно додаємо вершини та ребра, починаючи з кореня індексу 0
  add_edges(tree, heap, 0, pos)

  # Формуємо список кольорів вузлів у порядку внутрішнього переліку вершин графа
  colors = [data['color'] for _, data in tree.nodes(data=True)]
  # Готуємо словник міток: для кожної вершини беремо її атрибут 'label' (значення з heap)
  labels = {n: data['label'] for n, data in tree.nodes(data=True)}

  # Створюємо нове полотно для малювання з фіксованим розміром
  plt.figure(figsize=(8, 5))
  # Малюємо граф: передаємо позиції, підписи, вимикаємо стрілки, задаємо розмір і колір вузлів
  nx.draw(tree, pos=pos, labels=labels, arrows=False, node_size=2500, node_color=colors)
  # Відображаємо побудоване зображення на екрані
  plt.show()


# === Приклад використання (аналогічно до оригіналу, але замість ручного зв’язування вузлів — масив) ===

# Створюємо список, що представляє бінарну купу (heap),
# де для вузла з індексом i: left = 2*i + 1, right = 2*i + 2
heap = [0, 4, 1, 5, 10, 3]

# Викликаємо функцію візуалізації для побудови дерева за вмістом купи
draw_tree(heap)