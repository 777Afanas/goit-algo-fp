# Імпортуємо бібліотеку matplotlib для малювання графіків і ліній
import matplotlib.pyplot as plt
# Імпортуємо numpy для математичних обчислень (cos, sin, sqrt, pi)
import numpy as np


# Оголошуємо рекурсивну функцію, яка малює одну гілку дерева
def draw_branch(x, y, length, angle, depth):
    # Базовий випадок рекурсії: якщо depth = 0, малювання припиняється
    if depth == 0:
        return

    # --- Обчислюємо координати кінця поточної гілки ---
    # нова x-координата = x + length * cos(angle)
    x_end = x + length * np.cos(angle)
    # нова y-координата = y + length * sin(angle)
    y_end = y + length * np.sin(angle)

    # --- Малюємо гілку ---
    # малюємо відрізок від (x, y) до (x_end, y_end)
    # зелений колір, товщина лінії = 1
    plt.plot([x, x_end], [y, y_end], color='green', linewidth=1)

    # --- Підготовка до рекурсивних викликів ---
    # нова довжина гілки зменшується за правилом дерева Піфагора (в корені з двох разів)
    new_length = length * np.sqrt(2) / 2

    # --- Рекурсивний виклик для лівої гілки ---
    # кут збільшуємо на 45° (π/4), глибину зменшуємо на 1
    draw_branch(x_end, y_end, new_length, angle + np.pi / 4, depth - 1)

    # --- Рекурсивний виклик для правої гілки ---
    # кут зменшуємо на 45° (−π/4), глибину теж зменшуємо на 1
    draw_branch(x_end, y_end, new_length, angle - np.pi / 4, depth - 1)


# --- Налаштування полотна для малювання ---
# створюємо нову фігуру 8×8 дюймів
plt.figure(figsize=(8, 8))
# вимикаємо осі координат (буде чисте полотно)
plt.axis('off')


# --- Отримання глибини від користувача ---
DEFAULT_DEPTH = 8  # значення за замовчуванням
MAX_DEPTH = 15     # максимально дозволене значення

# просимо користувача ввести глибину (0–MAX_DEPTH)
# strip() видаляє пробіли з початку та кінця введеного рядка
raw = input(f"Введіть рівень рекурсії (0–{MAX_DEPTH}, Enter={DEFAULT_DEPTH}): ").strip()

# якщо користувач ввів щось непорожнє
if raw:
    try:
        # пробуємо перетворити введений рядок на ціле число
        depth = int(raw)
    except ValueError:
        # якщо конверсія не вдалася (наприклад, введено "abc")
        print(f"⚠️ Некоректне значення, ставимо {DEFAULT_DEPTH}.")
        depth = DEFAULT_DEPTH
else:
    # якщо користувач просто натиснув Enter
    depth = DEFAULT_DEPTH
    print(f"Обрано глибину {depth} (за замовчуванням).")


# --- Перевірка введеного значення ---
if depth > MAX_DEPTH:
    # якщо введене число більше за максимально дозволене
    print(f"⚠️ {depth} занадто велике! Обмежуємо до {MAX_DEPTH}.")
    depth = MAX_DEPTH
elif depth < 0:
    # якщо користувач ввів від’ємне число
    print("⚠️ Глибина не може бути від’ємною. Ставимо 0.")
    depth = 0


# --- Старт малювання ---
# викликаємо рекурсивну функцію для початкової "гілки"
# початкова точка (0, 0), початкова довжина = 1, кут = π/2 (тобто вгору)
draw_branch(x=0, y=0, length=1, angle=np.pi/2, depth=depth)

# встановлюємо однаковий масштаб по обох осях (щоб дерево не було сплющене)
plt.gca().set_aspect('equal')
# показуємо результат на екрані
plt.show()



