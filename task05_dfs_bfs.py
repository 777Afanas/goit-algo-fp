# Імпортуємо uuid — використаємо для генерації унікальних ідентифікаторів вузлів (Node.id)
import uuid
# Імпортуємо networkx — представимо дерево як орієнтований граф для зручної візуалізації
import networkx as nx
# Імпортуємо matplotlib — бібліотека для малювання графа на екрані
import matplotlib.pyplot as plt
# Імпортуємо heapq — щоб (за потреби) перетворити список на мін-купу перед побудовою дерева
import heapq
# Імпортуємо deque — ефективна черга для ітеративного обходу в ширину (BFS)
from collections import deque


# Оголошуємо клас вузла бінарного дерева (залишаємо просту й зрозумілу структуру)
class Node:
    # Конструктор приймає значення вузла та необов’язковий початковий колір
    def __init__(self, key, color="skyblue"):
        # Посилання на лівого нащадка (спочатку немає)
        self.left = None
        # Посилання на правого нащадка (спочатку немає)
        self.right = None
        # Значення вузла, яке виводитимемо в підписі
        self.val = key
        # Поточний колір вузла (може змінюватися під час обходів)
        self.color = color
        # Унікальний ідентифікатор вузла — зручно використовувати як ключ у графі та словниках
        self.id = str(uuid.uuid4())


# Функція додає у граф вершини та ребра, обходячи вказаний піддерево через left/right
def add_edges(graph, node, pos, x=0, y=0, layer=1):
    # Якщо вузла немає — завершуємо (нічого додавати)
    if node is None:
        # Повертаємо граф без змін
        return graph
    # Додаємо вершину у граф: ключ — node.id; атрибути — колір (для підсвітки) та label (для підпису)
    graph.add_node(node.id, color=node.color, label=node.val)
    # Якщо є лівий нащадок — додаємо ребро та спускаємося рекурсивно вліво
    if node.left:
        # Додаємо орієнтоване ребро батько→лівий_нащадок
        graph.add_edge(node.id, node.left.id)
        # Обчислюємо горизонтальне зміщення лівого вузла з урахуванням глибини (layer)
        l = x - 1 / (2 ** layer)
        # Запам’ятовуємо позицію лівого вузла (трохи лівіше й нижче)
        pos[node.left.id] = (l, y - 1)
        # Рекурсивно додаємо ліве піддерево
        add_edges(graph, node.left, pos, x=l, y=y - 1, layer=layer + 1)
    # Якщо є правий нащадок — додаємо ребро та спускаємося рекурсивно вправо
    if node.right:
        # Додаємо орієнтоване ребро батько→правий_нащадок
        graph.add_edge(node.id, node.right.id)
        # Обчислюємо горизонтальне зміщення правого вузла з урахуванням глибини (layer)
        r = x + 1 / (2 ** layer)
        # Запам’ятовуємо позицію правого вузла (трохи правіше й нижче)
        pos[node.right.id] = (r, y - 1)
        # Рекурсивно додаємо праве піддерево
        add_edges(graph, node.right, pos, x=r, y=y - 1, layer=layer + 1)
    # Повертаємо заповнений граф
    return graph


# Функція малює дерево: приймає корінь Node та мапу кольорів {node.id: "#RRGGBB"}
def draw_tree(tree_root, colors):
    # Створюємо порожній орієнтований граф
    tree = nx.DiGraph()
    # Встановлюємо початкову позицію кореня у центрі полотна
    pos = {tree_root.id: (0, 0)}
    # Наповнюємо граф вершинами, ребрами та позиціями, обходячи дерево згори вниз
    tree = add_edges(tree, tree_root, pos)
    # Формуємо список кольорів у тій самій послідовності, у якій networkx повертає вершини
    node_colors = [colors.get(node_id, 'skyblue') for node_id in tree.nodes()]
    # Формуємо словник підписів із атрибутів вузлів графа (label = значення вузла)
    labels = {nid: data['label'] for nid, data in tree.nodes(data=True)}
    # Створюємо фігуру фіксованого розміру для акуратного малювання
    plt.figure(figsize=(8, 5))
    # Малюємо граф: позиції, підписи, без стрілок, із заданим розміром і кольорами вузлів
    nx.draw(tree, pos=pos, labels=labels, arrows=False, node_size=2500, node_color=node_colors)
    # Відображаємо побудоване дерево на екрані
    plt.show()


# Функція будує Node-дерево зі списку (наприклад, масиву-купи) за індексами 2*i+1 і 2*i+2
def build_heap_tree(heap, index=0):
    # Якщо список порожній — повертаємо None (дерева немає)
    if not heap:
        # Вказуємо, що немає кореня
        return None
    # Створюємо список вузлів тієї ж довжини: для None у масиві ставимо None у вузлах
    nodes = [None if v is None else Node(v) for v in heap]
    # Проходимо всі позиції та зв’язуємо батька з дітьми за індексними формулами
    for i, node in enumerate(nodes):
        # Якщо вузла в цій позиції немає — пропускаємо
        if node is None:
            # Перехід до наступної позиції
            continue
        # Розраховуємо індекси лівого та правого нащадків
        li, ri = 2 * i + 1, 2 * i + 2
        # Якщо лівий індекс валідний і вузол існує — прив’язуємо
        if li < len(nodes) and nodes[li] is not None:
            # Присвоюємо посилання на лівого нащадка
            node.left = nodes[li]
        # Якщо правий індекс валідний і вузол існує — прив’язуємо
        if ri < len(nodes) and nodes[ri] is not None:
            # Присвоюємо посилання на правого нащадка
            node.right = nodes[ri]
    # Повертаємо корінь дерева (нульовий елемент)
    return nodes[0]


# Генеруємо колір у форматі #RRGGBB: поступово від темного до світлого залежно від кроку
def generate_color(step, total_steps):
    # Обчислюємо параметр t у [0,1]; якщо крок лише один — беремо найсвітліший тон
    t = 1.0 if total_steps <= 1 else step / (total_steps - 1)
    # Задаємо темну (початок) та світлу (кінець) точки градієнта в RGB
    dark = (16, 40, 80)          # темний синюватий
    light = (200, 230, 255)      # світло-блакитний
    # Лінійно інтерполюємо кожну з компонент R/G/B
    r = int(dark[0] + (light[0] - dark[0]) * t)
    g = int(dark[1] + (light[1] - dark[1]) * t)
    b = int(dark[2] + (light[2] - dark[2]) * t)
    # Повертаємо шістнадцятковий рядок у форматі #RRGGBB
    return f'#{r:02x}{g:02x}{b:02x}'


# Рахуємо кількість вузлів у дереві — знадобиться для нормалізації градієнта
def count_nodes(node):
    # Якщо піддерево порожнє — 0
    if node is None:
        # Немає вузлів
        return 0
    # 1 (цей вузол) + кількість вузлів ліворуч + кількість вузлів праворуч
    return 1 + count_nodes(node.left) + count_nodes(node.right)


# Ітеративний DFS: використовуємо стек, фарбуємо вузли у порядку відвідання
def dfs_visualize(root, total_steps):
    # Якщо дерева немає — повертати нічого
    if root is None:
        # Порожня мапа кольорів
        return {}
    # Стек з коренем для обходу в глибину
    stack = [root]
    # Множина відвіданих вузлів (за id), щоб не зациклитись
    visited = set()
    # Результуюча мапа {node.id: "#RRGGBB"} для малювання
    colors = {}
    # Лічильник кроків для градієнта
    step = 0
    # Поки є елементи у стеку — продовжуємо обхід
    while stack:
        # Беремо вузол з верхівки стеку (LIFO)
        node = stack.pop()
        # Пропускаємо None або вже відвіданий вузол
        if node is None or node.id in visited:
            # Переходимо до наступної ітерації
            continue
        # Позначаємо вузол як відвіданий
        visited.add(node.id)
        # Генеруємо колір для поточного кроку
        col = generate_color(step, total_steps)
        # Записуємо колір у мапу для візуалізації
        colors[node.id] = col
        # За бажанням оновимо і сам вузол (не обов’язково для малювання)
        node.color = col
        # Збільшуємо номер кроку
        step += 1
        # Кладемо у стек спочатку правого, потім лівого — так лівий дістанеться першим
        if node.right is not None:
            # Додаємо правого нащадка
            stack.append(node.right)
        if node.left is not None:
            # Додаємо лівого нащадка
            stack.append(node.left)
    # Повертаємо мапу кольорів вузлів у порядку їх відвідання
    return colors


# Ітеративний BFS: використовуємо чергу, фарбуємо вузли за рівнями зліва направо
def bfs_visualize(root, total_steps=1):
    # Якщо дерева немає — нічого повертати
    if root is None:
        # Порожня мапа кольорів
        return {}
    # Черга з кореня для обходу в ширину
    queue = deque([root])
    # Множина відвіданих вузлів (за id)
    visited = set()
    # Результуюча мапа {node.id: "#RRGGBB"}
    colors = {}
    # Лічильник кроків для градієнта
    step = 0
    # Поки у черзі є елементи — продовжуємо
    while queue:
        # Дістаємо вузол з початку черги (FIFO)
        node = queue.popleft()
        # Пропускаємо None або вже відвіданий вузол
        if node is None or node.id in visited:
            # Переходимо на наступну ітерацію
            continue
        # Позначаємо вузол як відвіданий
        visited.add(node.id)
        # Генеруємо колір для поточного кроку
        col = generate_color(step, total_steps)
        # Записуємо колір у мапу для подальшого малювання
        colors[node.id] = col
        # За бажанням оновлюємо колір всередині вузла (не критично для малювання)
        node.color = col
        # Переходимо до наступного кроку
        step += 1
        # Додаємо дітей у чергу: лівий першим, правий другим (рівневий порядок зліва направо)
        if node.left is not None:
            # Додаємо лівого нащадка у чергу
            queue.append(node.left)
        if node.right is not None:
            # Додаємо правого нащадка у чергу
            queue.append(node.right)
    # Повертаємо мапу кольорів вузлів у порядку їх відвідання
    return colors


# Головний блок запуску — спрощений, без дублювання коду для DFS і BFS
if __name__ == '__main__':
    # Створюємо вихідний список (масив), який інтерпретуємо як купу/індексне дерево
    heap = [1, 3, 5, 7, 9, 2, 4, 34, 2, 1, 2]
    # За потреби нормалізуємо масив до мін-купи, щоб відповідати властивості купи
    heapq.heapify(heap)
    # Будуємо Node-дерево з масиву за формулами індексів (left=2*i+1, right=2*i+2)
    root = build_heap_tree(heap)
    # Визначаємо загальну кількість вузлів — для плавного градієнта від темного до світлого
    total = count_nodes(root)
    # Послідовно виконуємо два обходи (DFS, BFS), щоб уникнути дублювання коду
    for traverse in (dfs_visualize, bfs_visualize):
        # Отримуємо мапу кольорів для поточного обходу (ітеративний стек/черга)
        colors = traverse(root, total)
        # Малюємо дерево, використовуючи отримані кольори вузлів
        draw_tree(root, colors)


