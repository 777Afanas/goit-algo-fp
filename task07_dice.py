# Імпортуємо модуль random для генерації випадкових чисел (імітація кидків кубиків)
import random

# Імпортуємо defaultdict, щоб автоматично створювати лічильники для кожної суми
from collections import defaultdict

# Імпортуємо datetime для фіксації часу у висновках
from datetime import datetime

# Імпортуємо Path для зручної роботи з файлом readme.md
from pathlib import Path


# ----- Параметри -----
# Встановлюємо кількість симуляцій (чим більше, тим точніше результати Монте-Карло)
nums = 1_000_000  

# Встановлюємо зерно генератора випадкових чисел для відтворюваності результатів
SEED = 42         

# Ініціалізуємо генератор випадкових чисел заданим зерном, якщо воно не None
if SEED is not None:
    random.seed(SEED)


# ----- Симуляція кидків двох кубиків -----
# Створюємо словник, який автоматично ініціалізує значення 0 для нових ключів
counts = defaultdict(int)

# Виконуємо цикл для nums кидків двох кубиків
for _ in range(nums):
    # Кидаємо перший кубик (випадкове число від 1 до 6)
    dice = random.randint(1, 6)
    # Кидаємо другий кубик (випадкове число від 1 до 6)
    dice_two = random.randint(1, 6)
    # Збільшуємо лічильник для суми двох кубиків
    counts[dice + dice_two] += 1

# Переконуємося, що у словнику є ключі для всіх можливих сум (2..12)
for s in range(2, 13):
    counts.setdefault(s, 0)


# ----- Ймовірності Монте-Карло -----
# Створюємо словник з ймовірностями для кожної суми:
# ділимо кількість випадінь на загальну кількість кидків
probabilities = {key: count / nums for key, count in counts.items()}


# ----- Аналітичні ймовірності (точно як у завданні) -----
# Задаємо кількість комбінацій, що дають кожну суму (2..12)
analytic_counts = {
    2: 1, 3: 2, 4: 3, 5: 4, 6: 5, 7: 6,
    8: 5, 9: 4, 10: 3, 11: 2, 12: 1
}

# Загальна кількість можливих результатів (6*6)
total_outcomes = 36

# Обчислюємо аналітичну ймовірність для кожної суми (n/36)
analytic = {s: analytic_counts[s] / total_outcomes for s in range(2, 13)}


# ----- Markdown-таблиця -----
# Друкуємо заголовок детальної таблиці для порівняння результатів
print("\n| Сума | Монте-Карло | Аналітична (теорія) | Абс. похибка | Відн. похибка |")
print("|-----:|-------------:|--------------------:|-------------:|--------------:|")

# Змінна для збереження найбільшої відносної похибки серед усіх сум
max_rel_err = 0.0

# Проходимо всі можливі суми від 2 до 12
for s in range(2, 13):
    # Ймовірність, отримана методом Монте-Карло
    mc = probabilities[s]
    # Аналітична ймовірність (з таблиці)
    an = analytic[s]
    # Абсолютна похибка між емпіричною та аналітичною ймовірністю
    abs_err = abs(mc - an)
    # Відносна похибка у відсотках
    rel_err = (abs_err / an * 100) if an > 0 else 0.0
    # Оновлюємо максимальну відносну похибку, якщо ця більша
    max_rel_err = max(max_rel_err, rel_err)

    # Формуємо рядок для аналітичної ймовірності у вигляді "X.XX% (n/36)"
    analytic_str = f"{an*100:.2f}% ({analytic_counts[s]}/36)"

    # Друкуємо рядок таблиці у форматі Markdown з усіма даними
    print("| {s:>4} | {mc:>11.2f}% | {an_str:>18} | {ae:>11.5f} | {re:>12.2f}% |".format(
        s=s, mc=mc*100, an_str=analytic_str, ae=abs_err, re=rel_err
    ))


# ----- Додавання висновків у readme.md -----
# Створюємо об'єкт шляху до файлу readme.md
readme_path = Path("readme.md")

# Якщо файл ще не існує — створюємо його та записуємо початковий текст
if not readme_path.exists():
    readme_path.write_text(
        "# Дослідження ймовірностей сум при киданні двох кубиків\n\n",         
        encoding="utf-8"
    )

# Отримуємо поточну дату та час для вставки у висновок
timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

# Формуємо список рядків з висновками, які будуть додані в кінець файлу
conclusion = [
    "\n",
    f"** Висновки (додано {timestamp})**",
    "",
    f"- Проведено {nums:,} симуляцій кидання двох кубиків. Отримані методом Монте-Карло ймовірності добре узгоджуються з аналітичними розрахунками.",
    f"- Максимальна відносна похибка серед сум: {max_rel_err:.2f}%.",
    "- Висновок: симуляція реалізована коректно; оцінки ймовірностей збігаються з аналітичними розрахунками в межах статистичної похибки."
]

# Відкриваємо файл readme.md у режимі дописування та додаємо нові рядки
with readme_path.open("a", encoding="utf-8") as f:
    f.write("\n".join(conclusion))