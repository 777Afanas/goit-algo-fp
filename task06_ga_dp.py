# ЖАДІБНИЙ ПІДХІД (Greedy) для задачі «максимум калорій при фіксованому бюджеті».
# Ідея: впорядковуємо страви за спаданням відношення калорії/вартість
# і беремо їх у такому порядку, доки вистачає бюджету.
# Це 0/1-вибір (кожну страву можна взяти не більше одного разу), без дроблення.
# Важливо: Greedy не гарантує глобально оптимального рішення для 0/1-випадку — це лише швидка евристика.
# Складність: O(n log n) через сортування + O(n) на один прохід.

def greedy_algorithm(items, budget):
    # Перетворюємо словник у список пар (назва, деталі), щоб мати впорядковану колекцію для сортування.
    pairs = list(items.items())

    # Сортуємо пари за спаданням співвідношення "калорії/вартість".
    # Використовуємо анонімну функцію (lambda) як ключ сортування:
    #   kv[1]["calories"] / kv[1]["cost"] — скільки калорій дістаємо з кожної одиниці вартості.
    # reverse=True означає, що найбільше співвідношення буде на початку.
    sorted_items = sorted(
        pairs,
        key=lambda kv: kv[1]["calories"] / kv[1]["cost"],
        reverse=True
    )

    # Ініціалізуємо накопичувач загальної калорійності вибраних страв.
    total_calories = 0
    # Ініціалізуємо змінну для відстеження невикористаного (залишкового) бюджету.
    remaining_budget = budget
    # Порожній список для фіксації назв страв, які ми беремо.
    chosen_items = []

    # Проходимо впорядкований список — від «найвигідніших» до «найменш вигідних».
    for name, details in sorted_items:
        # Зчитуємо вартість поточної страви (скільки потрібно бюджету, щоб її взяти).
        cost = details["cost"]
        # Зчитуємо калорійність поточної страви (скільки калорій отримаємо, якщо візьмемо).
        cals = details["calories"]

        # Перевіряємо, чи можемо дозволити собі цю страву в межах залишку бюджету.
        if cost <= remaining_budget:
            # Якщо так — «купуємо» її: зменшуємо залишок бюджету на вартість страви.
            remaining_budget -= cost
            # Додаємо її калорії до загальної суми.
            total_calories += cals
            # Запам’ятовуємо сам факт вибору (додаємо назву страви до підсумкового списку).
            chosen_items.append(name)
        # Якщо ні — просто переходимо до наступної, оскільки жадібний підхід не «перебирає» інші комбінації.

    # Обчислюємо фактично витрачену суму як різницю між початковим бюджетом і залишком.
    spent = budget - remaining_budget

    # Повертаємо кортеж з трьох компонентів:
    #   1) загальна калорійність вибраних страв,
    #   2) скільки коштів витрачено,
    #   3) перелік назв вибраних страв у порядку додавання.
    return total_calories, spent, chosen_items


# Реалізація динамічного програмування для задачі «вибір їжі з максимальною калорійністю при фіксованому бюджеті».
# ПІДХІД: використовуємо Нижній підхід (Bottom-Up), або «висхідне» ДП.
#   Ідея Bottom-Up: ми будуємо таблицю оптимальних значень для всіх підзадач «знизу вгору»:
#   спочатку вичислюємо найменші підзадачі (малі бюджети і короткі префікси списку страв),
#   а потім на їх основі — більші підзадачі (більші бюджети та більше страв).
#
# Порівняння з Верхнім підходом (Top-Down, мемоїзація):
#   - Top-Down формулює рекурсію «згори донизу» (від повної задачі до менших підзадач) і кешує (мемує) результати,
#     обчислюючи лише ті підзадачі, які реально потрібні. Це зручно для «розріджених» просторів станів.
#   - Bottom-Up наперед обчислює всі значення для прямокутної таблиці розміром (кількість_страв+1) × (бюджет+1).
#     Такий підхід простий, ітеративний, без рекурсії, часто з передбачуванішим використанням пам’яті/стеку.
#
# У цій реалізації також є етап «бек-трекінгу» для відновлення конкретного набору страв з побудованої таблиці.

def dynamic_programming(items, budget):
    # Формуємо впорядкований список назв страв, щоб мати фіксований індекс для кожної страви (зручно для таблиці ДП).
    item_names = list(items.keys())
    # Зберігаємо кількість страв (розмірність по «рядках» для таблиці ДП).
    n = len(item_names)
    # Будуємо список вартостей (cost) у тому ж порядку, що й item_names (індекс i відповідає страві item_names[i]).
    costs = [items[name]["cost"] for name in item_names]
    # Будуємо список калорійностей (calories) у тому ж порядку (узгоджений індекс з costs).
    calories = [items[name]["calories"] for name in item_names]

    # Ініціалізуємо 2D-таблицю ДП dp_table розміром (n+1) × (budget+1), заповнену нулями.
    # dp_table[i][b] означає «максимальна калорійність, яку можна отримати, використовуючи ПЕРШІ i страв при бюджеті b».
    dp_table = [[0 for _ in range(budget + 1)] for _ in range(n + 1)]

    # Заповнюємо таблицю ДП «знизу вгору»:
    # i пробігає від 1 до n (скільки перших страв доступно), b — від 0 до budget (який бюджет дозволено витратити).
    for i in range(1, n + 1):
        # Поточна страва має індекс i-1 (бо рядок i означає «перші i страв», індексація списків з нуля).
        cur_cost = costs[i - 1]      # Вартість поточної страви.
        cur_cals = calories[i - 1]   # Калорійність поточної страви.
        # Перебираємо всі можливі значення бюджету b.
        for b in range(0, budget + 1):
            # Якщо поточна страва «вміщується» у бюджет b, маємо вибір: взяти її або не брати.
            if cur_cost <= b:
                # «Взяти»: додаємо калорійність поточної страви + оптимум для бюджету (b - cur_cost) з попередніх (i-1) страв.
                take_value = cur_cals + dp_table[i - 1][b - cur_cost]
                # «Не брати»: залишаємо оптимум для бюджету b з попередніх (i-1) страв.
                skip_value = dp_table[i - 1][b]
                # Обираємо максимум між «взяти» та «не брати».
                dp_table[i][b] = max(take_value, skip_value)
            else:
                # Якщо поточну страву не можна взяти (не вистачає бюджету), оптимум такий самий, як без неї.
                dp_table[i][b] = dp_table[i - 1][b]

    # На цьому етапі dp_table[n][budget] містить максимальну досяжну калорійність для всіх n страв і бюджету budget.
    # Далі виконуємо «бек-трекінг», щоб відновити, ЯКІ саме страви були взяті для досягнення цього максимуму.

    # Порожній список для зібраних назв страв, що увійшли до оптимального рішення.
    chosen_items = []
    # temp_budget — робочий бюджет під час відновлення рішення (рухаємось «вгору» по таблиці).
    temp_budget = budget
    # Починаємо з i = n (рядок останньої «повної» підзадачі) і рухаємось до i = 0.
    i = n

    # Поки є що розглядати (i > 0) і бюджет не від’ємний, перевіряємо, чи брали ми страву i-ої позиції.
    while i > 0 and temp_budget >= 0:
        # Якщо значення з i стравами при бюджеті temp_budget ВІДРІЗНЯЄТЬСЯ від значення без i-ої страви,
        # це означає, що i-та страва була «взята» в оптимальному рішенні (бо «не брати» дало б той самий результат).
        if dp_table[i][temp_budget] != dp_table[i - 1][temp_budget]:
            # Додаємо назву цієї страви (індекс i-1) до списку обраних.
            chosen_items.append(item_names[i - 1])
            # Зменшуємо робочий бюджет на її вартість — переходимо до комірки, звідки прийшли, коли «брали» страву.
            temp_budget -= costs[i - 1]
        # У будь-якому випадку переходимо до розгляду попереднього рядка (i-1).
        i -= 1

    # Бек-трекінг додавав страви у зворотному порядку (від кінця до початку),
    # тож для «природного» відображення розгортаємо список.
    chosen_items.reverse()

    # Максимальна досяжна калорійність зчитується з правого нижнього кута таблиці.
    max_calories = dp_table[n][budget]
    # Обчислюємо сумарні витрати як суму вартостей уже відновлених обраних страв.
    spent = sum(items[name]["cost"] for name in chosen_items)

    # Повертаємо кортеж: (максимальна калорійність, фактично витрачено, перелік вибраних страв).
    return max_calories, spent, chosen_items


